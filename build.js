// Builds everything that derives from the components folder. Run: node build.js
// - index.js registers every element, one import per component folder, so a new component needs no
//   manual registration.
// - dist/ holds the classic sizes of every component in every status, as standalone .svg files that
//   need no JS (README, docs, diagram tools).
// - dist/isostack.isopack.json is an icon pack: the default size of every component in every status,
//   in the collection format that isoAtlas and Isoflow load as is ({ id, name, icons: [...] }).
// - custom-elements.json describes every tag for editors and docs tools.
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { draw, STATUSES } from './core/draw.js';

const root = new URL('./', import.meta.url);
const camel = name => name.replace(/-(\w)/g, (_, c) => c.toUpperCase());
const names = readdirSync(new URL('components/', root), { withFileTypes: true }).filter(d => d.isDirectory()).map(d => d.name).sort();
const models = [];
for (const name of names) models.push((await import(`./components/${name}/draw.js`))[camel(name)]);

writeFileSync(new URL('index.js', root), `// isostack: registers every element. Generated by build.js from the components folder: do not edit.
// Import this file to get them all, or one component file (components/<name>/iso-<name>.js) to load only that one.
${names.map(name => `import './components/${name}/iso-${name}.js';`).join('\n')}

// The base class of every element, so a page can test \`event.target instanceof IsoBox\`.
export { IsoBox } from './core/element.js';
`);

// dist/ is rebuilt from scratch, so that a removed size or component leaves no stale file.
const dist = new URL('dist/', root);
rmSync(dist, { recursive: true, force: true });
mkdirSync(dist, { recursive: true });
const pack = {
  type: 'isopack', version: 1, id: 'isostack', name: 'isostack',
  description: 'Isometric infrastructure icons in four statuses: ok, warn, down, unknown.',
  icons: [],
};
let files = 0;
for (const model of models) {
  for (const [width, depth] of model.sizes) {
    for (const status of STATUSES) {
      writeFileSync(new URL(`${model.name}-${width}x${depth}-${status}.svg`, dist), draw(model, { width, depth, status }));
      files++;
    }
  }
  for (const status of STATUSES) {
    pack.icons.push({
      id: `isostack-${model.name}-${status}`,
      name: `${model.title} (${status})`,
      url: `data:image/svg+xml;base64,${Buffer.from(draw(model, { status })).toString('base64')}`,
      isIsometric: true,
    });
  }
}
writeFileSync(new URL('isostack.isopack.json', dist), JSON.stringify(pack));

// custom-elements.json describes every tag in the standard Custom Elements Manifest format (schema
// 2.1.0), read by editors, Storybook and docs tools: each tag lists its attributes with this model's
// limits, its events and the CSS variables it reads.
const attr = (name, type, def, description) => ({ name, type: { text: type }, ...(def === undefined ? {} : { default: def }), description, fieldName: name });
const size = (model, k, what) => {
  const min = model.minimum[k], max = model.maximum?.[k];
  const range = min === max ? `fixed at ${min}` : max ? `from ${min} to ${max}` : `from ${min}`;
  return attr(k, 'number', String(model.defaults[k]), `${what} in ${k === 'height' ? '' : 'whole '}grid cells, ${range}.`);
};
const ref = (name, module) => ({ name, module });
const manifest = {
  schemaVersion: '2.1.0',
  modules: [
    { kind: 'javascript-module', path: 'core/element.js',
      declarations: [{ kind: 'class', name: 'IsoBox', description: 'The base class of every isostack element.', superclass: { name: 'HTMLElement', package: 'global:' } }],
      exports: [{ kind: 'js', name: 'IsoBox', declaration: ref('IsoBox', 'core/element.js') }] },
    ...names.map((name, i) => {
      const model = models[i], path = `components/${name}/iso-${name}.js`, className = `Iso${camel('-' + name)}`;
      return { kind: 'javascript-module', path,
        declarations: [{
          kind: 'class', name: className, customElement: true, tagName: `iso-${name}`,
          description: `${model.title}${model.container ? ', a container: open, it shows the elements standing inside' : ''}.`,
          superclass: ref('IsoBox', 'core/element.js'),
          attributes: [
            size(model, 'width', 'Width'), size(model, 'depth', 'Depth'), size(model, 'height', 'Height'),
            attr('status', STATUSES.map(s => `'${s}'`).join(' | '), "'ok'", 'Status color of the lights; absent or invalid means ok.'),
            attr('label', 'string', undefined, 'Text on the name plate; no plate when absent.'),
            attr('resizable', 'boolean', 'false', 'Shows the blue cubes that resize the element.'),
            ...(model.container ? [attr('open', 'boolean', 'false', 'The cover fades to show the inside and the child elements.')] : []),
            attr('paused', 'boolean', 'false', 'The lights stand still (an element out of view also pauses by itself).'),
            ...['x', 'y', 'z'].map(k => attr(k, 'number', '0', `Position in cells inside a container, or on a page grid (${k}).`)),
          ],
          events: [
            { name: 'input', type: { text: 'Event' }, description: 'At each cell gained or lost during a cube drag; read the new size on the element.' },
            { name: 'change', type: { text: 'Event' }, description: 'When a cube drag that changed the size ends.' },
          ],
          cssProperties: [
            { name: '--iso-speed', default: '1', description: 'Animation speed multiplier (2 = twice as fast).' },
            { name: '--iso-animation', default: 'running', description: 'paused freezes the animations.' },
            ...STATUSES.map(s => ({ name: `--iso-${s}`, syntax: '<color>', description: `Color of the ${s} status.` })),
          ],
        }],
        exports: [
          { kind: 'js', name: className, declaration: ref(className, path) },
          { kind: 'custom-element-definition', name: `iso-${name}`, declaration: ref(className, path) },
        ] };
    }),
  ],
};
writeFileSync(new URL('custom-elements.json', root), JSON.stringify(manifest, null, 2) + '\n');
console.log(`index.js: ${names.length} elements. dist/: ${files} files, and isostack.isopack.json with ${pack.icons.length} icons. custom-elements.json: ${names.length} tags.`);
